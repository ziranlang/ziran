#!/usr/bin/env python3
"""Honor generated cgo build constraints in legacy file-list compiler checks.

Generated projects normally use Go package builds. Some older checks pass a
list of .go files, which makes Go ignore explicit build constraints. Ask the
real Go tool which generated tagged companions are active before forwarding
that list; keep all other command behavior and diagnostics unchanged.
"""
import json
import os
from pathlib import Path
import subprocess
import sys


def main():
    assert sys.argv[1] == '--go'
    executable, args = sys.argv[2], sys.argv[3:]
    if args and args[0] in ('run', 'build', 'test'):
        candidates = {}
        selection_flags = []
        skip = False
        for index, arg in enumerate(args[1:], 1):
            if skip:
                skip = False
                continue
            if arg == '--':
                break
            if arg in ('-o', '-C', '-gcflags', '-asmflags', '-ldflags', '-tags',
                       '-modfile', '-pkgdir', '-overlay'):
                if arg == '-tags' and index + 1 < len(args):
                    selection_flags.extend((arg, args[index + 1]))
                skip = True
                continue
            if arg.startswith('-tags='):
                selection_flags.append(arg)
                continue
            path = Path(arg)
            if not arg.endswith('.go') or not path.is_file():
                continue
            prefix = path.read_text().splitlines()[:8]
            if any('Code generated by zi2go' in line for line in prefix) and any(
                    line.startswith('//go:build ') for line in prefix):
                candidates[arg] = path.resolve()
        ignored = set()
        for directory in {path.parent for path in candidates.values()}:
            result = subprocess.run([executable, 'list', '-e', '-json', *selection_flags, '.'], cwd=directory,
                                    capture_output=True, text=True)
            if result.returncode:
                continue
            try:
                metadata = json.loads(result.stdout)
            except ValueError:
                continue
            ignored.update(directory/name for name in metadata.get('IgnoredGoFiles', []))
        args = [arg for arg in args if candidates.get(arg) not in ignored]
    os.execv(executable, [executable, *args])


if __name__ == '__main__':
    main()
