import fcntl
import json
import os
from pathlib import Path
import shutil
import signal
import subprocess
import sys
import time

ziran, work = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve()
real_cc = shutil.which(os.environ.get('CC', 'cc'))
out = work/'out with spaces'
out.mkdir()
(work/'group').mkdir()
(work/'sub').mkdir()
for i in range(8): (work/f'group/m{i}.zi').write_text('Read :: () -> s32 { return 1 }\n')
imports = ''.join(f'M{i} :: #import "group/m{i}";\n' for i in range(8))
source = work/'sub/app.zi'

def program(extra):
    source.write_text(imports+'host :: #system_library "host";\n'
                      'Helper :: () -> s32 #foreign host "helper";\n'
                      '#program_export\nAnswer :: () -> s32 {\n'
                      'return Helper() + '+ ' + '.join(f'M{i}.Read()' for i in range(8))+f' + {extra}\n}}\n')

(work/'base.c').write_text('int base(void) { return 34; }\n')
subprocess.run([real_cc, '-c', str(work/'base.c'), '-o', str(work/'base.o')], check=True)
subprocess.run(['ar', 'rcs', str(work/'libbase.a'), str(work/'base.o')], check=True)
(out/'host.c').write_text('extern int base(void); int helper(void) { return base() + BUMP; }\n')
env = dict(os.environ, CC=real_cc, CFLAGS='-O2 -DBUMP=0', LDFLAGS='-L'+str(work), LDLIBS='-lbase')
command = [str(ziran), 'build', '--target=c', '--exe', '--entry', 'app:Answer', '--diagnostics=json',
           '--root', str(work), '--module-path', 'group='+str(work/'group'), '-o', str(out), str(source)]
program(0)
subprocess.run(command, env=env, check=True)
assert subprocess.run([str(out/'app')]).returncode == 42
# A stale nested source is not in this invocation's generated manifest. A
# stale root basename must not be confused with the reachable nested file.
(out/'dead').mkdir()
(out/'dead/old.c').write_text('/* Generated by zi2c from old.zi. */\n#error stale nested source\n')
(out/'app.c').write_text('/* Generated by zi2c from app.zi. */\n#error stale root source\n')
wrapper = work/'cc'
wrapper.write_text('''#!/usr/bin/env python3
import fcntl,json,os,subprocess,sys,time
from pathlib import Path
work=Path(os.environ['BUILD_TEST_DIR'])
compiling='-c' in sys.argv
with (work/'state.lock').open('w') as lock:
 fcntl.flock(lock,fcntl.LOCK_EX)
 state=json.loads((work/'state.json').read_text())
 if compiling:
  state['active']+=1;state['peak']=max(state['peak'],state['active']);state['started']+=1
 (work/'state.json').write_text(json.dumps(state))
if compiling:
 deadline=time.monotonic()+30
 while not (work/'compile.release').exists():
  if time.monotonic()>deadline:raise SystemExit(91)
  time.sleep(.01)
else:
 (work/'link.ready').touch()
 deadline=time.monotonic()+30
 while not (work/'link.release').exists():
  if time.monotonic()>deadline:raise SystemExit(92)
  time.sleep(.01)
 if os.environ.get('BUILD_FAIL_LINK')=='1':
  Path(sys.argv[sys.argv.index('-o')+1]).write_text('incomplete executable')
  raise SystemExit(3)
result=subprocess.run([os.environ['REAL_CC'],*sys.argv[1:]])
if compiling:
 with (work/'state.lock').open('w') as lock:
  fcntl.flock(lock,fcntl.LOCK_EX)
  state=json.loads((work/'state.json').read_text());state['active']-=1
  (work/'state.json').write_text(json.dumps(state))
raise SystemExit(result.returncode)
''')
wrapper.chmod(0o755)
env.update(CC=str(wrapper), REAL_CC=real_cc, BUILD_TEST_DIR=str(work))
children = []

def start(fail=False):
    log = (work/f'build-{len(children)}.log').open('wb')
    child = subprocess.Popen(command, env={**env, 'BUILD_FAIL_LINK': str(int(fail))},
                             stdout=log, stderr=log, start_new_session=True)
    log.close()
    children.append(child)
    return child

def until(predicate):
    deadline = time.monotonic()+30
    while not predicate():
        assert time.monotonic() < deadline, 'native build gate timed out'
        time.sleep(.01)

def state():
    with (work/'state.lock').open('w') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        return json.loads((work/'state.json').read_text())

def reset():
    (work/'state.json').write_text(json.dumps(dict(active=0, peak=0, started=0)))
    for name in ['compile.release', 'link.release', 'link.ready']:
        (work/name).unlink(missing_ok=True)

try:
    program(1)
    reset()
    first = start(fail=True)
    until(lambda: state()['active'] >= min(4, os.cpu_count() or 1))
    assert subprocess.run([str(out/'app')]).returncode == 42
    with (out/'.build.lock').open('r') as lock:
        try: fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError: pass
        else: raise AssertionError('output lock was not retained during compilation')
    (work/'compile.release').touch()
    until(lambda: (work/'link.ready').exists())
    assert subprocess.run([str(out/'app')]).returncode == 42
    (work/'link.release').touch()
    assert first.wait(timeout=30) != 0
    assert subprocess.run([str(out/'app')]).returncode == 42
    assert not list(out.glob('.app.*'))
    assert not (out/'app.c').exists()
    for line in (work/'build-0.log').read_text().splitlines():
        assert json.loads(line)['code'] == 'zir_c.toolchain'
    reset()
    first, second = start(), start()
    until(lambda: state()['active'] >= min(4, os.cpu_count() or 1))
    (work/'compile.release').touch()
    until(lambda: (work/'link.ready').exists())
    assert subprocess.run([str(out/'app')]).returncode == 42
    (work/'link.release').touch()
    assert first.wait(timeout=30) == second.wait(timeout=30) == 0
    assert 1 <= state()['peak'] <= 4
    if (os.cpu_count() or 1) > 1: assert state()['peak'] > 1
    assert subprocess.run([str(out/'app')]).returncode == 43
    assert not list(out.glob('.app.*'))
    print('Parallel native builds preserve flags, nested modules, output locks and atomic replacement')
finally:
    for child in children:
        if child.poll() is None:
            os.killpg(child.pid, signal.SIGTERM)
            child.wait(timeout=10)
