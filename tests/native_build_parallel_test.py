import fcntl
import json
import os
from pathlib import Path
import shutil
import signal
import subprocess
import sys
import time

ziran, work = Path(sys.argv[1]).resolve(), Path(sys.argv[2]).resolve()
real_cc = shutil.which(os.environ.get('CC', 'cc'))
available_cpus = len(os.sched_getaffinity(0)) if hasattr(os, 'sched_getaffinity') else (os.cpu_count() or 1)
workers = min(16, available_cpus)
out = work/'out with spaces'
out.mkdir()
(work/'group').mkdir()
(work/'sub').mkdir()
for i in range(16): (work/f'group/m{i:02d}.zi').write_text('Read :: () -> s32 { return 1 }\n')
imports = ''.join(f'M{i} :: #import "group/m{i:02d}";\n' for i in range(16))
source = work/'sub/app.zi'

def program(extra):
    source.write_text(imports+'host :: #system_library "host";\n'
                      'Helper :: () -> s32 #foreign host "helper";\n'
                      '#program_export\nAnswer :: () -> s32 {\n'
                      'return Helper() + '+ ' + '.join(f'M{i}.Read()' for i in range(16))+f' + {extra}\n}}\n')

(work/'base.c').write_text('int base(void) { return 26; }\n')
subprocess.run([real_cc, '-c', str(work/'base.c'), '-o', str(work/'base.o')], check=True)
subprocess.run(['ar', 'rcs', str(work/'libbase.a'), str(work/'base.o')], check=True)
(out/'host.c').write_text('extern int base(void); int helper(void) { return base() + BUMP; }\n')
env = dict(os.environ, CC=real_cc, CFLAGS='-O2 -DBUMP=0', LDFLAGS='-L'+str(work), LDLIBS='-lbase')
command = [str(ziran), 'build', '--target=c', '--exe', '--entry', 'app:Answer', '--diagnostics=json',
           '--root', str(work), '--module-path', 'group='+str(work/'group'), '-o', str(out), str(source)]
program(0)
subprocess.run(command, env=env, check=True)
assert subprocess.run([str(out/'app')]).returncode == 42
# The group package's modules are generated under their package identities.
first_source = next(path.name for path in out.glob('*m00.c'))
last_source = next(path.name for path in out.glob('*m15.c'))
# A stale nested source is not in this invocation's generated manifest. A
# stale root basename must not be confused with the reachable nested file.
(out/'dead').mkdir()
(out/'dead/old.c').write_text('/* Generated by zi2c from old.zi. */\n#error stale nested source\n')
(out/'app.c').write_text('/* Generated by zi2c from app.zi. */\n#error stale root source\n')
wrapper = work/'cc'
wrapper.write_text('''#!/usr/bin/env python3
import fcntl,json,os,subprocess,sys,time
from pathlib import Path
work=Path(os.environ['BUILD_TEST_DIR'])
compiling='-c' in sys.argv
source_path=next((a for a in sys.argv[1:] if a.endswith('.c')), '')
source=Path(source_path).name
with (work/'state.lock').open('w') as lock:
 fcntl.flock(lock,fcntl.LOCK_EX)
 state=json.loads((work/'state.json').read_text())
 if compiling:
  state['active']+=1;state['peak']=max(state['peak'],state['active']);state['started']+=1
  state['sources'].append(source_path)
  state['parents'].append(os.getppid())
  (work/('started-'+source)).write_text(str(os.getpid()))
 (work/'state.json').write_text(json.dumps(state))
if compiling:
 deadline=time.monotonic()+30
 while not (work/'compile.release').exists():
  if time.monotonic()>deadline:raise SystemExit(91)
  time.sleep(.01)
 if source==os.environ.get('BUILD_FAIL_SOURCE'):
  with (work/'state.lock').open('w') as lock:
   fcntl.flock(lock,fcntl.LOCK_EX)
   state=json.loads((work/'state.json').read_text());state['active']-=1
   (work/'state.json').write_text(json.dumps(state))
  (work/'failed').write_text(str(os.getpid()))
  os.write(2,b'forced compiler failure\\n')
  raise SystemExit(3)
 if os.environ.get('BUILD_MESSAGES')=='1':os.write(2,('scheduled '+source+'\\n').encode())
 if source==os.environ.get('BUILD_HOLD_SOURCE') or os.environ.get('BUILD_HOLD_OTHERS')=='1':
  if os.environ.get('BUILD_NOISE')=='1':
   for _ in range(32):os.write(2,b'compiler diagnostic bytes '*1024)
  (work/'hold.waiting').touch()
  while not (work/'hold.release').exists():
   if time.monotonic()>deadline:raise SystemExit(93)
   time.sleep(.01)
else:
 (work/'link.ready').touch()
 deadline=time.monotonic()+30
 while not (work/'link.release').exists():
  if time.monotonic()>deadline:raise SystemExit(92)
  time.sleep(.01)
 if os.environ.get('BUILD_FAIL_LINK')=='1':
  Path(sys.argv[sys.argv.index('-o')+1]).write_text('incomplete executable')
  raise SystemExit(3)
result=subprocess.run([os.environ['REAL_CC'],*sys.argv[1:]])
if compiling:
 with (work/'state.lock').open('w') as lock:
  fcntl.flock(lock,fcntl.LOCK_EX)
  state=json.loads((work/'state.json').read_text());state['active']-=1
  (work/'state.json').write_text(json.dumps(state))
raise SystemExit(result.returncode)
''')
wrapper.chmod(0o755)
env.update(CC=str(wrapper), REAL_CC=real_cc, BUILD_TEST_DIR=str(work))
children = []

def start(fail=False, *, mode='json', extra=None, affinity=None):
    log = (work/f'build-{len(children)}.log').open('wb')
    selected = [part if part != '--diagnostics=json' else '--diagnostics='+mode for part in command]
    child = subprocess.Popen(selected, env={**env, 'BUILD_FAIL_LINK': str(int(fail)), **(extra or {})},
                             stdout=log, stderr=log, start_new_session=True,
                             preexec_fn=(lambda: os.sched_setaffinity(0, affinity)) if affinity is not None else None)
    log.close()
    children.append(child)
    return child

def until(predicate):
    deadline = time.monotonic()+30
    while not predicate():
        assert time.monotonic() < deadline, 'native build gate timed out'
        time.sleep(.01)

def state():
    with (work/'state.lock').open('w') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        return json.loads((work/'state.json').read_text())

def reset():
    (work/'state.json').write_text(json.dumps(dict(active=0, peak=0, started=0, sources=[], parents=[])))
    for name in ['compile.release', 'link.release', 'link.ready', 'hold.release', 'hold.waiting', 'failed']:
        (work/name).unlink(missing_ok=True)
    for path in work.glob('started-*'): path.unlink()

try:
    program(1)
    reset()
    first = start(fail=True)
    until(lambda: state()['active'] >= workers)
    assert subprocess.run([str(out/'app')]).returncode == 42
    with (out/'.build.lock').open('r') as lock:
        try: fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError: pass
        else: raise AssertionError('output lock was not retained during compilation')
    (work/'compile.release').touch()
    until(lambda: (work/'link.ready').exists())
    assert subprocess.run([str(out/'app')]).returncode == 42
    (work/'link.release').touch()
    assert first.wait(timeout=30) != 0
    assert subprocess.run([str(out/'app')]).returncode == 42
    assert not list(out.glob('.app.*'))
    assert not (out/'app.c').exists()
    for line in (work/'build-0.log').read_text().splitlines():
        assert json.loads(line)['code'] == 'zir_c.toolchain'
    reset()
    first, second = start(), start()
    until(lambda: state()['active'] >= workers)
    (work/'compile.release').touch()
    until(lambda: (work/'link.ready').exists())
    assert subprocess.run([str(out/'app')]).returncode == 42
    (work/'link.release').touch()
    assert first.wait(timeout=30) == second.wait(timeout=30) == 0
    assert 1 <= state()['peak'] <= workers
    if available_cpus > 1: assert state()['peak'] > 1
    assert subprocess.run([str(out/'app')]).returncode == 43
    assert not list(out.glob('.app.*'))
    # A blocked first worker must not hold up the next source after another
    # worker finishes. Run both captured and inherited-output paths. The gate
    # is a causal scheduling check, not a performance timing threshold.
    for number, mode in enumerate(['json', 'text'], 2):
        if available_cpus < 2: break
        program(number)
        reset()
        index = len(children)
        profile = work/f'profile-{mode}.jsonl'
        first = start(mode=mode, extra={'BUILD_HOLD_SOURCE':first_source, 'BUILD_MESSAGES':'1', 'ZIRAN_PROFILE':str(profile)})
        until(lambda: state()['active'] >= workers)
        (work/'compile.release').touch()
        until(lambda: (work/'hold.waiting').exists())
        until(lambda: (work/('started-'+last_source)).exists())
        assert not (work/'hold.release').exists() and not (work/'link.ready').exists()
        assert 1 <= state()['peak'] <= workers
        assert subprocess.run([str(out/'app')]).returncode == 41 + number
        (work/'hold.release').touch()
        until(lambda: (work/'link.ready').exists())
        (work/'link.release').touch()
        assert first.wait(timeout=30) == 0
        assert subprocess.run([str(out/'app')]).returncode == 42 + number
        sample, = [json.loads(line) for line in profile.read_text().splitlines()]
        assert {'native.toolchain','native.objects','native.link'} <= {p['name'] for p in sample['phases']}
        assert sample['counters']['native_object_compile'] == len(state()['sources'])
        counters = sample['counters']
        assert counters.get('native_process_event',0)+counters.get('native_process_poll',0)==len(state()['sources'])+1
        assert counters.get('native_process_spawn',0)+counters.get('native_process_fork',0)==len(state()['sources'])+1
        if mode == 'json':
            import re
            records = [json.loads(line) for line in (work/f'build-{index}.log').read_text().splitlines()]
            names = re.findall(r'scheduled ([A-Za-z0-9_]+\.c)', '\n'.join(r['message'] for r in records))
            assert names == [Path(p).name for p in sorted(state()['sources'])], names
    # Drain a live worker's output after its bounded diagnostic buffer fills,
    # while the queue continues past the held worker.
    if available_cpus > 1:
        reset()
        index = len(children)
        first = start(extra={'BUILD_HOLD_SOURCE':first_source, 'BUILD_NOISE':'1'})
        (work/'compile.release').touch()
        until(lambda: (work/'hold.waiting').exists() and (work/('started-'+last_source)).exists())
        assert not (work/'link.ready').exists()
        (work/'hold.release').touch()
        until(lambda: (work/'link.ready').exists())
        (work/'link.release').touch()
        assert first.wait(timeout=30) == 0
        records = [json.loads(line) for line in (work/f'build-{index}.log').read_text().splitlines()]
        assert any('output truncated' in r['message'] for r in records), records
    if available_cpus > 1 and Path('/proc/self/stat').is_file():
        # Hold every other worker while one fails. Once that PID has been
        # reaped, no further compilation may start; all already-started
        # workers must still be drained and reaped before failure returns.
        program(4)
        reset()
        first = start(extra={'BUILD_FAIL_SOURCE':first_source, 'BUILD_HOLD_OTHERS':'1'})
        until(lambda: state()['active'] >= workers)
        (work/'compile.release').touch()
        until(lambda: (work/'failed').exists() and (work/'failed').read_text().strip())
        failed_pid = int((work/'failed').read_text())
        until(lambda: not Path('/proc',str(failed_pid)).exists())
        assert state()['started'] == workers
        assert not (work/'link.ready').exists()
        (work/'hold.release').touch()
        assert first.wait(timeout=30) != 0
        assert state()['started'] == workers and state()['active'] == 0
        assert not (work/'link.ready').exists()
        assert subprocess.run([str(out/'app')]).returncode == 45
    if Path('/proc/self/stat').is_file():
        # Compiler children must retain the output lock after their owned
        # builder dies, so a later build cannot race unfinished object writes.
        program(4)
        reset()
        first = start()
        until(lambda: state()['active'] >= workers)
        parents = set(state()['parents'])
        assert len(parents) == 1
        parent, = parents
        executable = Path('/proc', str(parent), 'cmdline').read_bytes().split(b'\0')[0]
        assert Path(os.fsdecode(executable)).name == 'zi2c', executable
        os.kill(parent, signal.SIGKILL)
        assert first.wait(timeout=30) != 0
        with (out/'.build.lock').open('r') as lock:
            try: fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError: pass
            else: raise AssertionError('compiler children lost the output lock')
        (work/'compile.release').touch()
        (work/'link.release').touch()
        until(lambda: state()['active'] == 0)
    # execvp accepts executable text without a shebang through /bin/sh.
    # posix_spawnp can reject that file with ENOEXEC; preserve the old behavior.
    program(4)
    shell_cc = work/'shell-cc'
    shell_cc.write_text('exec "$REAL_CC" "$@"\n')
    shell_cc.chmod(0o700)
    fallback_profile = work/'profile-shell.jsonl'
    selected = dict(env, CC=str(shell_cc), ZIRAN_PROFILE=str(fallback_profile))
    subprocess.run(command, env=selected, check=True, capture_output=True)
    sample, = map(json.loads, fallback_profile.read_text().splitlines())
    assert sample['counters'].get('native_process_spawn',0)+sample['counters'].get('native_process_fork',0)>0
    assert subprocess.run([str(out/'app')]).returncode == 46
    last_result = 46
    if hasattr(os, 'sched_setaffinity'):
        program(5)
        reset()
        profile = work/'profile-affinity.jsonl'
        first = start(extra={'ZIRAN_PROFILE': str(profile)}, affinity={min(os.sched_getaffinity(0))})
        until(lambda: state()['active'] >= 1)
        (work/'compile.release').touch()
        until(lambda: (work/'link.ready').exists())
        (work/'link.release').touch()
        assert first.wait(timeout=30) == 0
        sample, = map(json.loads, profile.read_text().splitlines())
        assert sample['counters']['native_worker_slots'] == 1
        assert state()['peak'] == 1 and state()['active'] == 0
        assert subprocess.run([str(out/'app')]).returncode == 47
        last_result = 47
    # Missing compilers must still produce one bounded JSON diagnostic and
    # leave the last complete executable intact.
    failed = subprocess.run(command, env=dict(env, CC=str(work/'absent-cc')), capture_output=True, text=True)
    assert failed.returncode != 0
    records = list(map(json.loads, failed.stderr.splitlines()))
    assert len(records) == 1 and records[0]['code'] == 'zir_c.toolchain', records
    assert 'cannot run' in records[0]['message'] and 'absent-cc' in records[0]['message']
    assert subprocess.run([str(out/'app')]).returncode == last_result
    print('Parallel native builds preserve flags, nested modules, output locks and atomic replacement')
finally:
    for child in children:
        if child.poll() is None:
            os.killpg(child.pid, signal.SIGTERM)
            child.wait(timeout=10)
